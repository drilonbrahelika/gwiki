export type Messages = typeof DEFAULT_MESSAGES;

/** Keys earlier versions used. Overrides of them are ignored, so an old config.json keeps loading. */
export const RETIRED_MESSAGES = new Set([
  'searchHint', 'spacesCount', 'itemsCount', 'byline', 'lastUpdated', 'synced',
  'updatedBy', 'updated', 'details', 'detailEditedBy', 'detailModified',
]);
export type MessageKey = keyof Messages;

export const format = (template: string, values: Record<string, string | number> = {}) =>
  template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
